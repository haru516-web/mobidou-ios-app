function createShrine<Id extends string>(
  id: Id,
  name: string,
  reading: string,
  place: string,
  theme: string,
  blessing: string,
  color: string,
  icon: string,
) {
  const landmark = place.split('・')[1] ?? '小さな宮';
  return {
    id,
    name,
    reading,
    place,
    theme,
    description: `${theme}\n歩いた先で、景色がひとつ変わる。\nモビーと${landmark}で、ご縁を結ぶ。`,
    blessing,
    stampLocation: '参拝後、境内の授与所で御朱印を授かる',
    color,
    icon,
  } as const;
}

