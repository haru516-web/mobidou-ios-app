// Builds the small pictures the 3D collection view uses, and the index that points at them.
//
// Why: on a real iPhone the 3D view (expo-gl) crashes when it uploads a WebP, and full-size pictures would also use
// over a gigabyte of graphics memory. So the 3D view gets its own copies: JPEG for pictures without transparency,
// PNG for those with it (keychains, characters), 384 px wide (backdrop 1024 px).
//
//   node scripts/build-space3d-assets.cjs           converts what is missing and rewrites the index
//   node scripts/build-space3d-assets.cjs --check   changes nothing; fails when a picture or the index is out of date
//
// Needs ffmpeg and ffprobe on the PATH. Run it again whenever a goshuin, keychain, character or the backdrop is added or changed.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'collection', 'space3d');
const INDEX = path.join(ROOT, 'src', 'data', 'space3dImages.ts');
const ITEM_WIDTH = 384;
const BACKDROP_WIDTH = 1024;
const check = process.argv.includes('--check');

const read = file => fs.readFileSync(path.join(ROOT, file), 'utf8');
/** `id: require('...')` lines inside the block that starts at `start` (a regex) and ends at the first line that is only `};`. */
function entries(file, start) {
  const lines = read(file).split(/\r?\n/);
  const from = lines.findIndex(line => start.test(line));
  if (from < 0) throw new Error(`${file}: ${start} not found`);
  const found = [];
  for (let i = from + 1; i < lines.length && !/^\s*[}\]]/.test(lines[i]); i++) {
    const match = lines[i].match(/^\s*(?:'([^']+)'|([A-Za-z0-9_]+)):\s*require\('([^']+)'\)/);
    if (match) found.push({ id: match[1] ?? match[2], source: path.resolve(ROOT, path.dirname(file), match[3]) });
  }
  if (!found.length) throw new Error(`${file}: nothing found after ${start}`);
  return found;
}
function pets(file) {
  const text = read(file);
  const found = [];
  for (const match of text.matchAll(/\bid:\s*'([A-Za-z0-9_-]+)',[\s\S]*?\bimage:\s*require\('([^']+)'\)/g)) found.push({ id: match[1], source: path.resolve(ROOT, path.dirname(file), match[2]) });
  return found;
}

const groups = {
  STAMPS: [...entries('src/data/shrines.ts', /^const BASE_STAMP_IMAGES\b/), ...entries('src/data/eventImages.ts', /^export const EVENT_GOSHUIN_IMAGES\b/)],
  KEYCHAINS: [...entries('src/data/collectionKeychains.ts', /^export const COLLECTION_KEYCHAINS\b/), ...entries('src/data/eventImages.ts', /^export const EVENT_KEYCHAIN_IMAGES\b/)],
  MOBBIES: pets('src/petCatalog.ts'),
};
const backdropFiles = [...read('src/components/collectionSpaceBackdrop.ts').matchAll(/require\('([^']+)'\)/g)].map(match => path.resolve(ROOT, 'src/components', match[1]));

const hasAlpha = file => /yuva|rgba|bgra|argb|abgr|gbra|ya8|ya16/.test(execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=pix_fmt', '-of', 'default=nw=1:nk=1', file]).toString());
function convert(source, name, width, alpha) {
  const target = path.join(OUT_DIR, name + (alpha ? '.png' : '.jpg'));
  const stale = !fs.existsSync(target) || fs.statSync(target).mtimeMs < fs.statSync(source).mtimeMs;
  if (stale) {
    if (check) throw new Error(`out of date: ${path.relative(ROOT, target)}`);
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', source, '-vf', `scale=${width}:-2`, ...(alpha ? [] : ['-q:v', '4']), target]);
  }
  return path.relative(path.join(ROOT, 'src', 'data'), target).split(path.sep).join('/');
}

if (!check) fs.mkdirSync(OUT_DIR, { recursive: true });
const lines = ['// Generated by scripts/build-space3d-assets.cjs. Do not edit by hand.', '/* eslint-disable */', ''];
const wanted = new Set();
for (const [group, list] of Object.entries(groups)) {
  const seen = new Set();
  lines.push(`export const SPACE3D_${group}: Record<string, any> = {`);
  for (const { id, source } of list) {
    if (seen.has(id)) continue;
    seen.add(id);
    const rel = convert(source, `${group.toLowerCase()}-${id}`, ITEM_WIDTH, hasAlpha(source));
    wanted.add(path.basename(rel));
    lines.push(`  '${id}': require('${rel}'),`);
  }
  lines.push('};', '');
}
lines.push('export const SPACE3D_BACKDROP: any[] = [');
backdropFiles.forEach((source, index) => {
  const rel = convert(source, `backdrop-${index + 1}`, BACKDROP_WIDTH, false);
  wanted.add(path.basename(rel));
  lines.push(`  require('${rel}'),`);
});
lines.push('];', '');

const text = lines.join('\n');
if (check) {
  if (!fs.existsSync(INDEX) || fs.readFileSync(INDEX, 'utf8') !== text) throw new Error(`out of date: ${path.relative(ROOT, INDEX)}`);
  console.log('space3d assets are up to date');
} else {
  fs.writeFileSync(INDEX, text);
  for (const file of fs.readdirSync(OUT_DIR)) if (!wanted.has(file)) fs.unlinkSync(path.join(OUT_DIR, file));
  console.log(`wrote ${wanted.size} pictures and ${path.relative(ROOT, INDEX)}`);
}
