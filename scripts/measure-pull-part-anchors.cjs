// Measures where each fixed accessory part (lens, cross, buttons) sits on the
// 1254px pull canvas, so the parts can ride the stretching body. Writes
// src/data/pullPartAnchors.ts. Needs ffmpeg (set FFMPEG or have it on PATH).
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const pullDir = path.join(root, 'assets/mobies/pull');
const ffmpeg = process.env.FFMPEG || 'ffmpeg';
const SIZE = 1254;
const prefixes = { mobirin: 'mobirin', mobichi: 'mobichi', yami: 'yami', mobiyan: 'mobiyan', mobiyura: 'yura', reomoby: 'reo', potemoby: 'pote', mobibou: 'mobibou', babumoby: 'babu' };
const parts = { lens: 'lens', cross: 'cross', buttonLeft: 'button-left', buttonRight: 'button-right' };

function measure(file) {
  const alpha = execFileSync(ffmpeg, ['-v', 'error', '-i', file, '-vf', 'alphaextract,format=gray', '-f', 'rawvideo', '-pix_fmt', 'gray', '-'], { maxBuffer: SIZE * SIZE * 2 });
  let minX = SIZE, minY = SIZE, maxX = -1, maxY = -1;
  for (let y = 0; y < SIZE; y += 1) for (let x = 0; x < SIZE; x += 1) {
    if (alpha[y * SIZE + x] > 128) {
      if (x < minX) minX = x; if (x > maxX) maxX = x;
      if (y < minY) minY = y; if (y > maxY) maxY = y;
    }
  }
  if (maxX < 0) throw new Error(`Empty part: ${file}`);
  return { x: +((minX + maxX) / 2 / SIZE).toFixed(4), y: +((minY + maxY) / 2 / SIZE).toFixed(4) };
}

const lines = ['// Generated by scripts/measure-pull-part-anchors.cjs. Centers as fractions of the pull canvas.',
  'export type PullPartAnchors = Record<\'lens\' | \'cross\' | \'buttonLeft\' | \'buttonRight\', { x: number; y: number }>;',
  'export const PULL_PART_ANCHORS: Record<string, PullPartAnchors> = {'];
for (const [id, prefix] of Object.entries(prefixes)) {
  const entries = Object.entries(parts).map(([key, name]) => {
    const center = measure(path.join(pullDir, `${prefix}-${name}.webp`));
    return `${key}: { x: ${center.x}, y: ${center.y} }`;
  });
  lines.push(`  ${id}: { ${entries.join(', ')} },`);
}
lines.push('};', '');
fs.writeFileSync(path.join(root, 'src/data/pullPartAnchors.ts'), lines.join('\n'));
console.log('wrote src/data/pullPartAnchors.ts');
